// Core is the single accessor to the pure core's helpers (conformance/spec/handler.md
// section 7): config parse and marshal, token parse and format, hex, nonce, key
// derivation and recovery decryption. It exists for the conformance adapter and the
// tests only and is not part of the public API. The pure members are rendered by
// conformance/tools/gen_core.py; derivation and recovery run the event core's own
// response path from a state that already holds the token.
package sh.tinfoil.ehbp

import EHBP.Token
import EHBPEvents.Event
import EHBPEvents.Phase
import EHBPEvents.Response as CoreResponse
import EHBPEvents.State
import EHBPEvents.Upload
import okhttp3.Response
import sh.tinfoil.ehbp.client.outcome
import sh.tinfoil.ehbp.identity.SessionRecoveryToken
import sh.tinfoil.ehbp.protocol.Code
import sh.tinfoil.ehbp.protocol.ProtocolError
import sh.tinfoil.ehbp.protocol.ResponseNonceHeader
import sh.tinfoil.ehbp.residue.Exchange
import sh.tinfoil.ehbp.residue.bytes
import sh.tinfoil.ehbp.residue.headerSeq
import sh.tinfoil.ehbp.residue.seq
import sh.tinfoil.ehbp.residue.str
import sh.tinfoil.ehbp.residue.string
import sh.tinfoil.ehbp.residue.unwrap
import java.math.BigInteger

object Core {
    // core:begin (generated by conformance/tools/gen_core.py; do not edit)
    // core: the pure helpers over the core, bytes and strings in and out (handler.md section 7).

    /** The public key of the first key configuration in `config` (RFC 9458, SPEC 3.2). */
    fun parseConfig(config: ByteArray): ByteArray {
        return bytes(unwrap(EHBP.__default.ParseConfig(seq(config))))
    }

    /** The RFC 9458 key configuration for `publicKey` under the pinned suite; the key id is opaque and always 0. */
    fun marshalConfig(publicKey: ByteArray): ByteArray {
        return bytes(unwrap(EHBP.__default.MarshalConfig(seq(publicKey))))
    }

    /** `publicKey` itself once the core has checked its length. */
    fun checkPublicKey(publicKey: ByteArray): ByteArray {
        return bytes(unwrap(EHBP.__default.CheckPublicKey(seq(publicKey))))
    }

    /** `nonceBase` XOR `seqNo`, big-endian in the last 8 bytes (SPEC 4.4). */
    fun nonceFor(nonceBase: ByteArray, seqNo: ULong): ByteArray {
        return bytes(unwrap(EHBP.__default.NonceFor(seq(nonceBase), seqNo.toLong())))
    }

    /** Lowercase hex. */
    fun encodeHex(data: ByteArray): String {
        return string(EHBP.__default.EncodeHex(seq(data)))
    }

    /** Strict hex decoding; none on any malformation. */
    fun decodeHex(hex: String): ByteArray? {
        return EHBP.__default.DecodeHex(str(hex)).takeIf { it.is_Some }?.let { bytes(it.dtor_value()) }
    }

    /** The SPEC 6.1.1 JSON form of a token from its two hex fields. */
    fun formatToken(exportedSecretHex: String, requestEncHex: String): String {
        return string(EHBPEvents.__default.FormatToken(str(exportedSecretHex), str(requestEncHex)))
    }

    /** The token of a SPEC 6.1.1 JSON document; any malformation is INVALID_TOKEN. */
    fun parseToken(json: String): SessionRecoveryToken {
        // shortcut: the core's ParseString is quadratic in Java (acc + [c] per char), so a huge document exhausts the heap; drop when the core accumulates linearly
        if (json.length > 4096) throw ProtocolError(Code.InvalidToken, "token document is too long") // two 64-hex members plus any formatting
        val fields = EHBPEvents.__default.ParseToken(str(json))
        val t = unwrap(EHBP.__default.ValidateTokenFields(fields.dtor__0(), fields.dtor__1()))
        return SessionRecoveryToken(bytes(t.dtor_exportedSecret()), bytes(t.dtor_requestEnc()))
    }
    // core:end

    /** deriveKeys returns the response key and nonce base derived from the token and the response nonce (SPEC 4.4). */
    fun deriveKeys(exportedSecret: ByteArray, requestEnc: ByteArray, responseNonce: ByteArray): Pair<ByteArray, ByteArray> {
        val x = recovery(SessionRecoveryToken(exportedSecret, requestEnc), null)
        x.feed(Event.create_ResponseHead(BigInteger.valueOf(200), headerSeq(listOf(ResponseNonceHeader to encodeHex(responseNonce))), false))
        x.failure?.let { throw it }
        val keys = x.state.dtor_phase().dtor_response().dtor_keys()
        return bytes(keys.dtor_key()) to bytes(keys.dtor_baseNonce())
    }

    /**
     * decryptWithToken returns a view of the response whose body is the
     * incremental authenticated plaintext stream derived from the token alone
     * (SPEC 6.2). Closing the replacement body closes the original body.
     */
    fun decryptWithToken(resp: Response, token: SessionRecoveryToken): Response {
        if (resp.body == null) throw ProtocolError(Code.InvalidInput, "response has no body")
        val x = recovery(token, resp)
        x.feed(Event.create_ResponseHead(BigInteger.valueOf(resp.code.toLong()), headerSeq(resp.headers), resp.priorResponse?.isRedirect == true))
        x.failure?.let { throw it }
        if (x.passthrough) throw ProtocolError(Code.MissingResponseNonce, "missing $ResponseNonceHeader header")
        return outcome(x)
    }

    /** recovery is an exchange holding token and awaiting an encrypted response head, with resp as the native response. */
    private fun recovery(token: SessionRecoveryToken, resp: Response?): Exchange {
        val d = State.Default()
        val awaiting = Phase.create_Exchanging(Upload.create_UpDone(), CoreResponse.create_AwaitHead(true))
        val core = Token.create(seq(token.exportedSecret), seq(token.requestEnc))
        val state = State.create(awaiting, d.dtor_origin(), d.dtor_publicKey(), d.dtor_verb(), d.dtor_url(), d.dtor_headers(), 0L, false, core, d.dtor_ctx())
        return Exchange(state).also { it.response = resp }
    }
}
