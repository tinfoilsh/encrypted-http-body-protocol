#!/usr/bin/env python3
"""Checks that every language's residue file declares the canonical bindings in
the canonical order (conformance/spec/handler.md, section 4), that `perform`
names every action tag, that every generated region (crypto, session, pump,
conversions, mapping) matches what `gen.py residue` renders and the client's
shim region what `gen.py shim` renders, every conformance adapter what
`gen.py adapter` renders, every `core` test accessor what `gen.py core`
renders, the error files and the FFI coders likewise, and reports line
counts; --matrix prints the per-binding table, a `*` on the rows that are
generated (the HTTP performers are hand-written), then the shim table
(generated lines per entry point and the hand-written rest per language), the
core table and the adapter table. Exit 1 on a missing or misordered symbol, a
file over budget, or drift."""
from __future__ import annotations

import re
import sys
from pathlib import Path

from gen import adapter, core, errors, ffi, residue, shim

ROOT = Path(__file__).resolve().parents[2]

EVENT_CANONICAL = [
    "x25519", "hmacSha256", "aeadSeal", "aeadOpen", "randomBytes",
    "send", "write", "read", "close",
    "beginSession", "publishToken", "clearToken", "token",
    "perform", "run",
    "seq", "bytes", "str", "string", "headerSeq", "headerPairs",
    "code", "error",
]
ACTION_TAGS = ["BeginSession", "PublishToken", "ClearToken", "RandomBytes", "X25519", "HmacSha256",
               "AeadSeal", "AeadOpen", "Send", "Write", "Read", "Close"]

# declaration regex per language (group 1 = name)
PATTERNS = {
    "go": r"^(?:type|func(?: \([^)]*\))?) (\w+)",
    "python": r"^\s*(?:class|def) (\w+)",
    "kotlin": r"^\s*(?:internal |private |override |open )*(?:class|object|fun) (\w+)",
    "rust": r"^\s*(?:pub(?:\(crate\))? )?(?:struct|enum|trait|fn|impl(?: [\w:]+ for)?) (\w+)",
    "js": r"^\s*(?:export )?(?:(?:class|function|async function|const) (\w+)|(?:async |static |private |readonly )*(\w+)\([^)]*\)(?:: [^{]+)? \{)",
    "swift": r"^\s*(?:public |private |internal |fileprivate |static |final |mutating |override )*(?:func|class|struct|enum|typealias) (\w+)",
}

# file, line budget, declaration regex, the canonical names the language has no
# need for (Swift's bytes and strings cross the FFI as they are).
EVENT_LANGUAGES = {
    "go": ("internal/eventresidue/residue.go", 520, PATTERNS["go"], set()),
    "python": ("python/src/ehbp/_residue.py", 350, PATTERNS["python"], set()),
    "kotlin": ("kotlin/src/main/kotlin/sh/tinfoil/ehbp/residue/Residue.kt", 400, PATTERNS["kotlin"], set()),
    "rust": ("rust/src/residue.rs", 500, PATTERNS["rust"], set()),
    "js": ("js/src/residue.ts", 450, PATTERNS["js"], set()),
    "swift": ("swift/Sources/EHBP/Residue.swift", 400, PATTERNS["swift"], {"seq", "bytes", "str", "string"}),
}


def norm(name: str) -> str:
    return name.replace("_", "").lower()


def declarations(path: Path, pattern: str) -> list[str]:
    names = []
    for line in path.read_text().splitlines():
        m = re.match(pattern, line)
        if m:
            name = next((g for g in m.groups() if g), None)
            if name:
                names.append(name)
    return names


def bodies(path: Path, pattern: str, spans: list[tuple[int, int]] = ()) -> dict[str, list[str]]:
    """Declaration name -> its lines up to the next declaration; a name declared
    inside one of the generated `spans` (1-based line ranges) gets a `*`. A
    repeated name (the decrypted body's own read/close after the performers)
    gets a `#n` suffix so it never lands in a canonical row."""
    out, current = {}, None
    for n, line in enumerate(path.read_text().splitlines(), 1):
        m = re.match(pattern, line)
        if m:
            name = next((g for g in m.groups() if g), None)
            if name:
                current = norm(name) + ("*" if any(a <= n <= b for a, b in spans) else "")
                if current in out:
                    current += f"#{sum(k.split('#')[0] == current for k in out) + 1}"
                out.setdefault(current, [])
        if current:
            out[current].append(line)
    return out


def matrix(langs: list[str]) -> None:
    """Line count of each binding per language; the comparable table. A `*`
    marks a cell generated by `gen.py residue` (the pump included); the rest is hand-written."""
    table = {}
    for lang in langs:
        rel, _, pattern, _ = EVENT_LANGUAGES[lang]
        path = ROOT / rel
        table[lang] = bodies(path, pattern, residue.spans(lang)) if path.exists() else {}
    print(f"{'binding':14}" + "".join(f"{l:>8}" for l in langs) + "   (* generated)")
    for name in EVENT_CANONICAL:
        cells = []
        for lang in langs:
            body, gen = table[lang].get(norm(name)), table[lang].get(norm(name) + "*")
            cells.append(f"{len(gen):>7}*" if gen else f"{len(body):>8}" if body else f"{'-':>8}")
        print(f"{name:14}" + "".join(cells))


def shim_matrix(langs: list[str]) -> None:
    """Generated lines of each shim entry point per language (gen_shim.py), the
    region total, and the hand-written rest of the client file (imports, native
    option types, hooks; tests excluded)."""
    table = {lang: shim.counts(lang) for lang in langs}
    print(f"\n{'shim':14}" + "".join(f"{l:>8}" for l in langs) + "   (generated by gen_shim.py)")
    for row in shim.PARTS + ["generated", "hand"]:
        print(f"{row:14}" + "".join(f"{table[lang][row]:>8}" for lang in langs))


def core_matrix() -> None:
    """Generated lines of each `core` test accessor (gen_core.py) and the
    hand-written rest of its file (the exchange-driven helpers, the native
    token type, imports); Swift's accessor is the whole `Core` enum over the ABI."""
    langs = core.LANGS
    table = {lang: core.counts(lang) for lang in langs}
    print(f"\n{'core':14}" + "".join(f"{l:>8}" for l in langs) + "   (generated by gen_core.py)")
    for row in ("generated", "hand"):
        print(f"{row:14}" + "".join(f"{table[lang][row]:>8}" for lang in langs))


def adapter_matrix() -> None:
    """Generated lines of each conformance adapter (gen_adapter.py) and the
    hand-written rest of its directory (Go's server operations and RSS probe);
    Swift's adapter is hand-written."""
    langs = adapter.LANGS
    table = {lang: adapter.counts(lang) for lang in langs}
    print(f"\n{'adapter':14}" + "".join(f"{l:>8}" for l in langs) + "   (generated by gen_adapter.py)")
    for row in ("generated", "hand"):
        print(f"{row:14}" + "".join(f"{table[lang][row]:>8}" for lang in langs))


def check_events(lang: str) -> bool:
    rel, budget, pattern, absent = EVENT_LANGUAGES[lang]
    path = ROOT / rel
    if not path.exists():
        print(f"{lang:7} MISSING {rel}")
        return False
    found = [norm(n) for n in declarations(path, pattern)]
    missing, cursor = [], 0
    for want in EVENT_CANONICAL:
        if want in absent:
            continue
        try:
            cursor = found.index(norm(want), cursor) + 1
        except ValueError:
            missing.append(want)
    text = path.read_text()
    perform = bodies(path, pattern).get("perform", [])
    perform_text = "\n".join(perform)
    tags_missing = [t for t in ACTION_TAGS if t.lower() not in perform_text.lower()]  # Swift's cases are lowerCamel
    lines = sum(1 for _ in path.open())
    drift = {**residue.drift(lang), **shim.drift(lang)}
    ok = not missing and not tags_missing and lines <= budget and not drift
    print(f"{lang:7} {'ok  ' if ok else 'FAIL'} {lines:4d}/{budget} lines  missing-or-misordered={missing or '-'}  perform-lacks={tags_missing or '-'}  generated={'drift in ' + ','.join(drift) if drift else 'ok'}")
    if drift:
        target = "shim" if "shim" in drift else "residue"
        print(f"        diff: python3 conformance/tools/gen.py --check {target}; fix: python3 conformance/tools/gen.py {target}")
    return ok


if __name__ == "__main__":
    args = sys.argv[1:]
    if args and args[0] == "--events":  # kept for old invocations; events is the only profile
        args.pop(0)
    show_matrix = False
    if args and args[0] == "--matrix":
        show_matrix = True
        args.pop(0)
    langs = args or list(EVENT_LANGUAGES)
    results = [check_events(l) for l in langs]
    # The error files (from the core), the adapters (from operations.md), the
    # FFI coders (from the Dafny datatypes) and the `core` accessors (from the
    # ABI's op list) are generated; drift in any fails.
    for target in (errors, adapter, ffi, core):
        if target.main(["--check"]) != 0:
            results.append(False)
    if show_matrix:
        matrix(langs)
        shim_matrix(langs)
        core_matrix()
        adapter_matrix()
    sys.exit(0 if all(results) else 1)
