"""The `core` test accessor of every SDK (handler.md section 7): the pure
helpers the conformance adapter and the tests call, one member per ACCESSOR
entry, rendered into the `core:begin`..`core:end` region of each SDK's
accessor file. ACCESSOR is drawn from ffi.OPS, the C ABI's op list with its
argument and result types, so the five accessors and the Swift `Core` enum
(every op, over the ABI) come from one list. The template
`templates/<lang>/core.*.j2` is the member form; the profile's `core`
section spells the call per Dafny module, the argument wrapper
and result statement per type, and the one op that is not one call
(`ParseToken`). What stays hand-written is the helpers that run an exchange
and the native token type."""
from __future__ import annotations

import sys
from types import SimpleNamespace

from . import ROOT, fill, markers, profile, snake, spell, template
from . import ffi

GEN = "generated by conformance/tools/gen_core.py; do not edit"
LANGS = ["go", "python", "kotlin", "rust", "js", "swift"]
PROFILE_KEYS = ["files", "comment", "end_gap", "region_indent", "casing", "types", "core"]
SIGS = {name: (args, res) for name, _, args, res in ffi.OPS}
MODULE = {name: module for name, module, _, _ in ffi.OPS}
# The accessor: the ABI ops that take and return bytes and strings only.
# ParseToken is the ABI's ParseToken then ValidateTokenFields in one call, so
# no Option<string> crosses; its result is the native token type.
ACCESSOR = [(n, *SIGS[n]) for n in ["ParseConfig", "MarshalConfig", "CheckPublicKey", "NonceFor", "EncodeHex", "DecodeHex", "FormatToken"]]
ACCESSOR.append(("ParseToken", SIGS["ParseToken"][0], SIGS["ValidateTokenFields"][1]))
DOC = {
    "ParseConfig": "The public key of the first key configuration in `config` (RFC 9458, SPEC 3.2).",
    "MarshalConfig": "The RFC 9458 key configuration for `publicKey` under the pinned suite; the key id is opaque and always 0.",
    "CheckPublicKey": "`publicKey` itself once the core has checked its length.",
    "NonceFor": "`nonceBase` XOR `seqNo`, big-endian in the last 8 bytes (SPEC 4.4).",
    "EncodeHex": "Lowercase hex.",
    "DecodeHex": "Strict hex decoding; none on any malformation.",
    "FormatToken": "The SPEC 6.1.1 JSON form of a token from its two hex fields.",
    "ParseToken": "The token of a SPEC 6.1.1 JSON document; any malformation is INVALID_TOKEN.",
}


def member(lang: str, op: tuple) -> SimpleNamespace:
    """One accessor member: its name, parameter list, return type, doc and body."""
    name, args, res = op
    C = profile(lang).core
    native = {a: (snake(a) if profile(lang).casing == "snake" else a) for a, _ in args}
    wrapped = {a: fill(C["wrap"][t], x=native[a]) for a, t in args}
    default = fill(C["call"][MODULE[name]], fn=name, args=", ".join(wrapped[a] for a, _ in args))
    pre, expr = C["overrides"].get(name, ("", default))
    body = fill(pre, **wrapped) + ("\n" if pre else "") + fill(C["ret"][res], expr=fill(expr, **wrapped))
    params = ", ".join(fill(C["param"], name=native[a], type=profile(lang).types[t]) for a, t in args)
    return SimpleNamespace(name=spell(lang, name), params=params, returns=C["returns"][res], doc=DOC[name], body=body)


def swift_op(op: tuple) -> SimpleNamespace:
    """One `Core` static func over the ABI: encode the arguments, call, decode the result."""
    S = profile("swift")
    fn, _, args, res = op
    t = ffi.parse_type(res)
    throws = isinstance(t, tuple) and t[0] == "app" and t[1] == "Result"
    enc = "; ".join(sum((S.ffi_enc(a, ffi.parse_type(at), "w") for a, at in args), []))
    return SimpleNamespace(
        name=S.ffi_case(fn), throws=throws, ret=S.ffi_ty(t[2][0] if throws else t),
        params=", ".join(f"_ {a}: {S.ffi_ty(ffi.parse_type(at))}" for a, at in args),
        setup="var w = Writer(); " + enc if enc else "let w = Writer()",
        result="try r." + S.ffi_name(t) + "()" if throws else S.ffi_dec(t, "r."),
    )


def render(lang: str) -> str:
    P = profile(lang)
    if lang == "swift":
        body = template(lang, "core").render(ops=[swift_op(op) for op in ffi.OPS])
    else:
        body = template(lang, "core").render(members=[member(lang, op) for op in ACCESSOR])
    return markers.wrap(P.comment, "core", GEN, body.removesuffix("\n"), P.region_indent.get("core", ""), P.end_gap)


def path(lang: str):
    return ROOT / profile(lang).files["core"]


def region(lang: str) -> tuple[str, str, str]:
    return markers.split(path(lang).read_text(), profile(lang).comment, "core")


def drift(lang: str) -> dict[str, str]:
    """{"core": unified diff} when the file's region differs from the rendering, else {}."""
    _, current, _ = region(lang)
    d = markers.diff(current, render(lang), f"{profile(lang).files['core']} (core)")
    return {"core": d} if d else {}


def write(lang: str) -> None:
    path(lang).write_text(markers.replace(path(lang).read_text(), profile(lang).comment, "core", render(lang)))


def main(argv: list[str]) -> int:
    check = "--check" in argv
    langs = [a for a in argv if a != "--check"] or LANGS
    bad = False
    for lang in langs:
        if check:
            d = drift(lang)
            bad |= bool(d)
            print("".join(d.values()) or f"{lang:7} core in sync")
        else:
            write(lang)
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
