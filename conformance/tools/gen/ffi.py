"""The coders of the C ABI between the Rust bundle of the core and the Swift
SDK (conformance/spec/swift-ffi.md), rendered from the Dafny datatype
declarations (`dafny_decls`) into the `ffi:begin`..`ffi:end` region of
rust/ffi/src/lib.rs (the Rust encoder and decoder, the `call` op table, a
test that round-trips every constructor) and swift/Sources/EHBP/Core.swift
(the Swift types and their coders). What crosses the ABI is ROOTS plus the
signatures in OPS; the closure over their field types gets a coder, in
declaration order, and a type the coders cannot encode fails loudly. Every
op must exist in the core with the listed arity. This module is the type
model; the profiles' `ffi_*` helpers spell one language each, and
`templates/<lang>/ffi.*.j2` is the file skeleton."""
from __future__ import annotations

import sys
from functools import cache
from types import SimpleNamespace

from . import ROOT, dafny_decls, markers, profile, template

GEN = "generated by conformance/tools/gen_ffi.py from the Dafny datatypes; do not edit"
LANGS = ["rust", "swift"]
PROFILE_KEYS = ["files", "ffi_ty", "ffi_name", "ffi_enc", "ffi_dec", "ffi_coder"]
SOURCES = ["dafny/ehbp.dfy", "dafny/ehbp_events.dfy"]
MODULES = ("EHBP", "EHBPEvents")  # the modules whose types cross the ABI

# The pure helpers of ehbp_call, in op order: (Dafny function, module, named argument types, result type).
OPS = [
    ("ParseConfig", "EHBP", [("config", "bytes")], "Result<bytes>"),
    ("MarshalConfig", "EHBP", [("publicKey", "bytes")], "Result<bytes>"),
    ("CheckPublicKey", "EHBP", [("publicKey", "bytes")], "Result<bytes>"),
    ("MakeOrigin", "EHBP", [("scheme", "string"), ("host", "string"), ("port", "Option<int>"), ("hasUserinfo", "bool")], "Result<Origin>"),
    ("ParseToken", "EHBPEvents", [("json", "string")], "(Option<string>, Option<string>)"),
    ("ValidateTokenFields", "EHBP", [("exportedSecretHex", "Option<string>"), ("requestEncHex", "Option<string>")], "Result<Token>"),
    ("FormatToken", "EHBPEvents", [("exportedSecretHex", "string"), ("requestEncHex", "string")], "string"),
    ("EncodeHex", "EHBP", [("data", "bytes")], "string"),
    ("DecodeHex", "EHBP", [("hex", "string")], "Option<bytes>"),
    ("NonceFor", "EHBP", [("nonceBase", "bytes"), ("seqNo", "uint64")], "Result<bytes>"),
    ("CodeString", "EHBP", [("code", "Code")], "string"),
    ("SessionApply", "EHBPEvents", [("store", "SessionStore"), ("action", "SessionAction")], "SessionStore"),
    ("NewSession", "EHBPEvents", [], "SessionStore"),
    ("SelfCheckActions", "EHBPEvents", [], "seq<Action>"),
    ("SelfCheckJudge", "EHBPEvents", [("results", "seq<Event>")], "seq<string>"),
]
# What else crosses: ehbp_state_new's constructor arguments, Step's event and actions, KeysOf's result.
ROOTS = ["Origin", "bytes", "Token", "Event", "seq<Action>", "Option<(bytes, bytes)>"]

PRIMITIVES = {"bool", "int", "nat", "uint64", "string"}
BYTES = ("seq", "uint8")
parse_type = dafny_decls.parse_type


@cache
def decls() -> dafny_decls.Decls:
    d = dafny_decls.parse_files([ROOT / rel for rel in SOURCES], MODULES)
    for name, module, args, _ in OPS:
        f = d.functions.get(name)
        if f is None:
            raise SystemExit(f"ffi: op {name} is not a function or const of {', '.join(MODULES)}")
        if f.module != module or len(f.params) != len(args):
            raise SystemExit(f"ffi: op {name} is {f.module}.{name}/{len(f.params)} in the core, listed as {module}.{name}/{len(args)}")
    return d


def datatypes() -> dict[str, dafny_decls.Datatype]:
    return decls().datatypes


def aliases() -> dict[str, object]:
    return decls().aliases


# --- the type model ----------------------------------------------------------


def resolve(t):
    """Aliases of primitives and of bytes dissolve; an alias of a structured type
    (Headers) keeps its name and gets a coder of its own; newtypes stay names."""
    if isinstance(t, str) and t in aliases():
        target_ = resolve(aliases()[t])
        return target_ if isinstance(target_, str) or target_ == BYTES else t
    if isinstance(t, str) and t.endswith("?"):
        raise SystemExit(f"unsupported type {t}")
    return t


def target(t):
    """The structure under a named type: an alias's target, a datatype's constructors
    with the type parameters substituted."""
    if isinstance(t, str) and t in aliases():
        return aliases()[t]
    name, args = (t[1], t[2]) if isinstance(t, tuple) and t[0] == "app" else (t, [])
    d = datatypes()[name]
    if len(args) != len(d.params):
        raise SystemExit(f"{name} takes {len(d.params)} type arguments")
    sub = dict(zip(d.params, args))
    return [(c, [(f, sub.get(ft, ft) if isinstance(ft, str) else ft) for f, ft in fs]) for c, fs in d.ctors]


def is_alias(t) -> bool:
    return isinstance(t, str) and t in aliases()


def is_named(t) -> bool:
    """A type that gets a coder of its own (a datatype, an instantiation, a structured alias)."""
    t = resolve(t)
    return (isinstance(t, str) and (t in datatypes() or t in aliases())) or (isinstance(t, tuple) and t[0] == "app")


def is_single(t) -> bool:
    """A datatype with one constructor carries no tag."""
    t = resolve(t)
    return not is_alias(t) and len(target(t)) == 1


def check(t) -> None:
    t = resolve(t)
    if isinstance(t, str):
        if t not in PRIMITIVES and not is_named(t):
            raise SystemExit(f"unsupported type {t!r} (newtypes other than uint64 do not cross the ABI)")
    elif t == BYTES:
        pass
    elif t[0] == "seq":
        check(t[1])
    elif t[0] == "tuple":
        for x in t[1]:
            check(x)
    elif t[0] == "app":
        for x in t[2]:
            check(x)
        if t[1] not in datatypes():
            raise SystemExit(f"unknown generic datatype {t[1]}")


def collect(t, seen: list) -> None:
    """Every named type reachable from `t`, each once, in a depth-first order."""
    t = resolve(t)
    check(t)
    if t == BYTES:
        return
    if isinstance(t, tuple) and t[0] in ("seq", "tuple"):
        for x in (t[1] if t[0] == "tuple" else [t[1]]):
            collect(x, seen)
        return
    if not is_named(t) or t in seen:
        return
    seen.append(t)
    if is_alias(t):
        collect(aliases()[t], seen)
        return
    for _, fields in target(t):
        for _, ft in fields:
            collect(ft, seen)


def coders() -> list:
    """The named types the ABI crosses, in declaration order of their datatype
    (or alias) and, for instantiations of one generic, in first-use order."""
    seen: list = []
    for t in ROOTS:
        collect(parse_type(t), seen)
    for _, _, args, res in OPS:
        for a in [t for _, t in args] + [res]:
            collect(parse_type(a), seen)
    order = list(aliases()) + list(datatypes())
    base = lambda t: t[1] if isinstance(t, tuple) else t  # noqa: E731
    return sorted(seen, key=lambda t: (order.index(base(t)), seen.index(t)))


def part(t) -> list[str]:
    """Name pieces of a type, for the coder of an instantiation (Option<(bytes, bytes)> -> option, bytes, bytes)."""
    t = resolve(t)
    if t == BYTES:
        return ["bytes"]
    if isinstance(t, str):
        return [t]
    if t[0] == "seq":
        return ["seq"] + part(t[1])
    if t[0] == "tuple":
        return sum((part(x) for x in t[1]), [])
    return [t[1]] + sum((part(x) for x in t[2]), [])


def module_of(t) -> str:
    """The Dafny module declaring a datatype or instantiation."""
    return datatypes()[t[1] if isinstance(t, tuple) else t].module


# --- rendering ---------------------------------------------------------------


def render(lang: str) -> str:
    P = profile(lang)
    types = coders()
    named = [SimpleNamespace(type=t, name=P.ffi_name(t), single=is_single(t)) for t in types if not is_alias(t)]
    body = template(lang, "ffi").render(
        gen=GEN, types=types, named=named,
        aliases=[SimpleNamespace(name=t, ty=P.ffi_ty(aliases()[t])) for t in types if is_alias(t)],
        coders=[P.ffi_coder(t) for t in types],
        ops=[SimpleNamespace(index=i, body=P.ffi_op(op)) for i, op in enumerate(OPS)] if hasattr(P, "ffi_op") else [],
    )
    return body.removesuffix("\n")


def path(lang: str):
    return ROOT / profile(lang).files["ffi"]


def region(lang: str) -> tuple[str, str, str]:
    return markers.split(path(lang).read_text(), "//", "ffi")


def drift(lang: str) -> str:
    _, current, _ = region(lang)
    return markers.diff(current, render(lang), f"{profile(lang).files['ffi']} (ffi)")


def main(argv: list[str]) -> int:
    check_ = "--check" in argv
    langs = [a for a in argv if a != "--check"] or LANGS
    bad = False
    for lang in langs:
        if check_:
            d = drift(lang)
            bad |= bool(d)
            print(d or f"{lang:7} ffi in sync")
        else:
            path(lang).write_text(markers.replace(path(lang).read_text(), "//", "ffi", render(lang)))
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
