"""The generated regions of the six residues (handler.md section 4): the
crypto bindings, the session store, the pump (`pump`), the conversions and
the error mapping, each between `<section>:begin` and `<section>:end`
markers and replaced in place. The crypto section is
`templates/<lang>/crypto.*.j2` over the Action and Event datatypes: one
primitive per CRYPTO action, with the profile's `crypto` (pre, expr) pair
as its body and `(ok, bytes)` as its result when the result event has two
fields. The other sections are the `session`, `conversions` and `mapping`
macros of `templates/<lang>/residue.*.j2`, reading the profile's `lock`,
`lock_field` and `types`. The HTTP performers are the native surface and
are written by hand under the residue's `http` header."""
from __future__ import annotations

import sys
from types import SimpleNamespace

from . import ROOT, errors, fill, macro, markers, profile, pump, spell, template

GEN = "generated by conformance/tools/gen_residue.py; do not edit"
LANGS = ["go", "python", "kotlin", "rust", "js", "swift"]
PROFILE_KEYS = ["files", "comment", "end_gap", "region_indent", "casing", "param", "types", "crypto", "lock", "lock_field", "pump"]
CRYPTO = ["X25519", "HmacSha256", "AeadSeal", "AeadOpen", "RandomBytes"]
SECTIONS = ["crypto", "session", "pump", "conversions", "mapping"]


def primitives(lang: str) -> list[SimpleNamespace]:
    """One per CRYPTO action: name, parameter list, setup lines, the native expression."""
    P = profile(lang)
    actions, events = pump.datatype("Action"), pump.datatype("Event")
    results = {tag: evs[0] for tag, _, evs in pump.PUMP if evs}
    out = []
    for tag in CRYPTO:
        pre, expr = P.crypto[tag]
        params = ", ".join(fill(P.param, name=f, type=P.types[t]) for f, t in actions[tag])
        out.append(SimpleNamespace(name=spell(lang, tag), params=params, pre=pre, expr=expr,
                                   open=len(events[results[tag]]) > 1, **{"async": tag in P.pump.get("awaits", ())}))
    return out


def render(lang: str, section: str) -> str:
    P = profile(lang)
    if section == "pump":
        return pump.render(lang)
    if section == "crypto":
        body = template(lang, "crypto").render(primitives=primitives(lang)).removesuffix("\n")
    else:
        context = dict(lock=P.lock, lock_field=P.lock_field, codes=errors.codes(lang) if lang in errors.LANGS else [], **P.types)
        body = macro(lang, "residue", section, context)
    return markers.wrap(P.comment, section, GEN, body, P.region_indent.get(section, ""), P.end_gap)


def path(lang: str):
    return ROOT / profile(lang).files["residue"]


def region(lang: str, section: str) -> tuple[str, str, str]:
    return markers.split(path(lang).read_text(), profile(lang).comment, section)


def drift(lang: str) -> dict[str, str]:
    """Section -> unified diff of the file's region against the rendering; only the drifted ones."""
    out = {}
    for section in SECTIONS:
        _, current, _ = region(lang, section)
        d = markers.diff(current, render(lang, section), f"{profile(lang).files['residue']} ({section})")
        if d:
            out[section] = d
    return out


def spans(lang: str) -> list[tuple[int, int]]:
    """(first, last) line numbers, 1-based, of each generated region in the file."""
    return [markers.lines(*region(lang, section)[:2]) for section in SECTIONS]


def write(lang: str) -> None:
    for section in SECTIONS:
        path(lang).write_text(markers.replace(path(lang).read_text(), profile(lang).comment, section, render(lang, section)))


def main(argv: list[str]) -> int:
    check = "--check" in argv
    langs = [a for a in argv if a != "--check"] or LANGS
    bad = False
    for lang in langs:
        if check:
            d = drift(lang)
            bad |= bool(d)
            print("".join(d.values()) or f"{lang:7} residue in sync")
        else:
            write(lang)
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
