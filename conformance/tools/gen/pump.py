"""The pump loop (`perform` and `run`, conformance/spec/pump.md) of every
residue, rendered from one action list (PUMP), the Event and Action
datatypes of dafny/ehbp_events.dfy (`dafny_decls`) and the language's
template `templates/<lang>/pump.*.j2`, whose `perform(cases)` and
`run(terminals)` macros are the two functions with one branch per case
kind. The profile's `pump` section spells how a core field converts to a
native value, how a native value wraps into an event field, the binding
call per section and the outcome statements per terminal action. The
region between the `pump:begin` and `pump:end` markers of each residue is
replaced in place."""
from __future__ import annotations

import sys
from types import SimpleNamespace

from . import ROOT, ffi, fill, lower, macro, markers, profile, spell

GEN = "generated by conformance/tools/gen_pump.py; do not edit"
LANGS = ["go", "python", "kotlin", "rust", "js", "swift"]
PROFILE_KEYS = ["files", "comment", "end_gap", "region_indent", "casing", "pump"]

# pump.md: action -> (kind, result events). `event` wraps one native result,
# `none` has no result, `open` unpacks a tuple, `chunk` is a tuple or a failure,
# `write` has no result but ends this lane when the sink is gone.
PUMP = [
    ("BeginSession", "event", ["SessionBegun"]),
    ("PublishToken", "none", []),
    ("ClearToken", "none", []),
    ("RandomBytes", "event", ["RandomResult"]),
    ("X25519", "event", ["X25519Result"]),
    ("HmacSha256", "event", ["HmacResult"]),
    ("AeadSeal", "event", ["AeadSealResult"]),
    ("AeadOpen", "open", ["AeadOpenResult"]),
    ("Send", "chunk", ["ResponseHead", "StreamFailed"]),
    ("Write", "write", []),
    ("Read", "chunk", ["Chunk", "StreamFailed"]),
    ("Close", "none", []),
]
TERMINAL = ["EmitPlaintext", "Passthrough", "Done", "Finished", "Discovered", "Fail"]
SESSION = {"BeginSession", "PublishToken", "ClearToken"}
CRYPTO = {"RandomBytes", "X25519", "HmacSha256", "AeadSeal", "AeadOpen"}


def datatype(name: str) -> dict[str, list[tuple[str, str]]]:
    """{constructor: [(field, type name)]} of Event or Action; the field types are plain names."""
    return {c: [(f, t if isinstance(t, str) else "/".join(map(str, t))) for f, t in fields] for c, fields in ffi.datatypes()[name].ctors}


def section_of(tag: str) -> str:
    return "session" if tag in SESSION else "crypto" if tag in CRYPTO else "http"


def event(lang: str, events: dict, name: str, values: dict[str, str]) -> str:
    """The event constructor; each field is wrapped by type from a local of the same name."""
    K = profile(lang).pump
    fields = events[name]
    vals = [values.get(f) or fill(K["wrap"].get(t, K["wrap"]["*"]), v=K["names"].get(f, f)) for f, t in fields]
    named = ", ".join(f if v == f else f"{f}: {v}" for (f, _), v in zip(fields, vals))
    labeled = ", ".join(f"{f}: {v}" for (f, _), v in zip(fields, vals))  # Swift's associated values, none when the case has no fields
    return fill(K["event"], ev=name, lev=lower(name), args=", ".join(vals), named=f" {named} " if named else "", labeled=f"({labeled})" if labeled else "")


def cases(lang: str) -> list[SimpleNamespace]:
    """One per PUMP action: the case test, the binding call, the locals the
    result unpacks into, the result event from those locals (`event`) or with
    the call inline as its one field (`event_inline`), and the failure event."""
    K = profile(lang).pump
    actions, events = datatype("Action"), datatype("Event")
    if [t for t, _, _ in PUMP] != [t for t in actions if t not in TERMINAL]:
        raise SystemExit("PUMP must list the dfy actions in order")

    def conv(f: str, t: str, arg: bool = False) -> str:
        table = {**K["conv"], **K.get("arg", {})} if arg else K["conv"]
        return fill(table.get(t, table["*"]), f=f)

    out = []
    for tag, kind, evs in PUMP:
        fields = actions[tag]
        args = [conv(f, t, arg=kind != "write") for f, t in fields]
        call = f"{K['recv'][section_of(tag)]}{spell(lang, tag)}({', '.join(args)})"
        if tag in K.get("awaits", ()):
            call = fill(K["awaited"], call=call)
        locals_ = K["locals"].get(tag) or ", ".join(f for f, _ in events[evs[0]]) if evs else ""
        inline = {events[evs[0]][0][0]: fill(K["wrap"].get(events[evs[0]][0][1], K["wrap"]["*"]), v=call)} if kind == "event" else {}
        # a failure of an action that names no stream (Send) is the response stream's
        failed = event(lang, events, evs[1], {} if "stream" in dict(fields) else {"stream": K["resp_body"]}) if len(evs) > 1 else ""
        out.append(SimpleNamespace(tag=tag, kind=kind, test=test(lang, tag, fields), call=call, locals=locals_,
                                   event=event(lang, events, evs[0], {}) if evs else "",
                                   event_inline=event(lang, events, evs[0], inline) if evs else "", failed=failed))
    return out


def test(lang: str, tag: str, fields: list[tuple[str, str]]) -> str:
    """The case label: a tag test, or the pattern binding the tag's fields."""
    K = profile(lang).pump
    form = K["test"] if fields or "test_nullary" not in K else K["test_nullary"]
    return fill(form, tag=tag, ltag=lower(tag), fields=", ".join(f for f, _ in fields))


def terminals(lang: str) -> list[SimpleNamespace]:
    """One per terminal action: the case test, the outcome statements and the exit."""
    K = profile(lang).pump
    actions = datatype("Action")
    out = []
    for tag in TERMINAL:
        fields = {f: fill(K["conv"].get(t, K["conv"]["*"]), f=f) for f, t in actions[tag]}
        body = [fill(s, **fields) for s in K["outcome"][tag]]
        out.append(SimpleNamespace(tag=tag, test=test(lang, tag, actions[tag]), body=body, exit=K["exit"].get(tag, K["exit"]["*"])))
    return out


def render(lang: str) -> str:
    P = profile(lang)
    perform = macro(lang, "pump", "perform", cases=cases(lang))
    perform = P.pump["postprocess"](perform) if "postprocess" in P.pump else perform
    body = perform + "\n\n" + macro(lang, "pump", "run", terminals=terminals(lang))
    return markers.wrap(P.comment, "pump", GEN, body, P.region_indent.get("pump", ""), P.end_gap)


def path(lang: str):
    return ROOT / profile(lang).files["residue"]


def region(lang: str) -> tuple[str, str, str]:
    return markers.split(path(lang).read_text(), profile(lang).comment, "pump")


def drift(lang: str) -> str:
    """A unified diff of the file's region against the rendering; empty when in sync."""
    _, current, _ = region(lang)
    return markers.diff(current, render(lang), f"{profile(lang).files['residue']} (file)")


def write(lang: str) -> None:
    path(lang).write_text(markers.replace(path(lang).read_text(), profile(lang).comment, "pump", render(lang)))


def main(argv: list[str]) -> int:
    check = "--check" in argv
    langs = [a for a in argv if a != "--check"] or LANGS
    bad = False
    for lang in langs:
        if check:
            d = drift(lang)
            bad |= bool(d)
            print(d or f"{lang:7} pump in sync")
        else:
            write(lang)
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
