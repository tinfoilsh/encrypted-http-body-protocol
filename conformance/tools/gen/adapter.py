"""The conformance adapters (conformance/adapters/<lang>), whole files
rendered from the operations table of conformance/spec/operations.md
(`operations_md`), the shape of each operation (OPS) and the constants every
adapter must agree on (CONST). The template `templates/<lang>/adapter.*.j2`
is the adapter with the dispatch as a loop over `cases`; the profile's
`adapter` section spells each pure operation and dispatch line. A snippet
naming an input the spec does not list for its operation fails to render,
and an operation missing from either side fails the run."""
from __future__ import annotations

import sys
from types import SimpleNamespace

from . import ROOT, fill, markers, operations_md, profile, template

GEN = "generated by conformance/tools/gen_adapter.py; do not edit"
LANGS = ["go", "python", "js", "rust", "kotlin"]
PROFILE_KEYS = ["files", "adapter"]
SPEC = ROOT / "conformance/spec/operations.md"

# operation -> (shape, flags). `exchange` flags: body (bytes | stream |
# pattern), hold (read the token 500 ms after sending, before the head),
# early (one byte, then close), after (token once the exchange ended), rss.
# `hardening` flags: target (header | cross | credentials). `server` names
# the hand-written Go function and runs nowhere else.
OPS = {
    "derive_keys": ("pure", {}),
    "decrypt_response": ("decrypt", dict(streaming=False)),
    "decrypt_response_streaming": ("decrypt", dict(streaming=True)),
    "compute_nonce": ("pure", {}),
    "token_roundtrip": ("pure", {}),
    "parse_config": ("pure", {}),
    "marshal_config": ("pure", {}),
    "decrypt_request": ("server", dict(fn="decryptRequest")),
    "middleware_request": ("server", dict(fn="middlewareRequest")),
    "request": ("exchange", dict(body="bytes")),
    "discover": ("discover", {}),
    "reject_reserved_header": ("hardening", dict(target="header")),
    "reject_cross_origin": ("hardening", dict(target="cross")),
    "residue_selfcheck": ("selfcheck", {}),
    "reject_url_credentials": ("hardening", dict(target="credentials")),
    "large_body": ("exchange", dict(body="pattern", rss=True)),
    "request_stream": ("exchange", dict(body="stream")),
    "close_response_early": ("exchange", dict(body="bytes", early=True)),
    "token_before_response": ("exchange", dict(body="bytes", hold=True)),
    "token_after_exchange": ("exchange", dict(body="bytes", after=True)),
}
EXCHANGE_FLAGS = ["hold", "early", "after", "rss"]
STR_INPUTS = {"seqHex", "json", "mutation", "target", "header"}
INT_INPUTS = {"keyId", "size_bytes", "block_seed", "zeroFrameCount"}

# What every adapter agrees on, by construction.
CONST = dict(
    nonce_header="Ehbp-Response-Nonce",
    header_subset=["ehbp-response-nonce", "content-length", "transfer-encoding", "content-type"],
    probe_path="/probe",
    cross_origin="http://other.invalid/probe",
    hold_ms=500,
    reserved_value="0" * 64,
    host_value="attacker.invalid",
    block_shift=20,
)


def spec_ops() -> dict[str, list[str]]:
    return operations_md.parse(SPEC.read_text())


def cases(lang: str) -> list[SimpleNamespace]:
    """(operation, body) per dispatch case, in OPS order."""
    A = profile(lang).adapter
    spec = spec_ops()
    if set(spec) != set(OPS):
        raise SystemExit(f"operations.md and OPS disagree: {sorted(set(spec) ^ set(OPS))}")
    out = []
    for op, (shape, flags) in OPS.items():
        if shape == "server" and not A.get("server"):
            continue
        if shape == "pure":
            kind = lambda n: "str" if n in STR_INPUTS else "int" if n in INT_INPUTS else "hex"  # noqa: E731
            inputs = {n: fill(A["inputs"][kind(n)], name=n) for n in spec[op]}
            try:
                body = fill(A["pure"][op], **inputs)
            except KeyError as err:
                raise SystemExit(f"{lang} adapter: {op} names the input {err} that operations.md does not list") from None
        else:
            kw = {k: A["bools"][v] if isinstance(v, bool) else v for k, v in flags.items()}
            if shape == "exchange":
                kw.update({f: A["bools"][bool(flags.get(f))] for f in EXCHANGE_FLAGS})
            body = fill(A["call"][shape], **kw)
        out.append(SimpleNamespace(op=op, body=body))
    return out


def render(lang: str) -> str:
    return template(lang, "adapter").render(gen=GEN, cases=cases(lang), **CONST).rstrip("\n") + "\n"


def path(lang: str):
    return ROOT / profile(lang).files["adapter"]


def drift(lang: str) -> str:
    current = path(lang).read_text() if path(lang).exists() else ""
    return markers.diff(current, render(lang), profile(lang).files["adapter"])


def counts(lang: str) -> dict[str, int]:
    """`generated`: lines of the rendered file; `hand`: lines of the other
    source files in the adapter directory (Go's server.go and rss_*.go)."""
    p = path(lang)
    others = [q for q in p.parent.rglob(f"*{p.suffix}") if q != p and "target" not in q.parts and "build" not in q.parts]
    return {"generated": render(lang).count("\n"), "hand": sum(q.read_text().count("\n") for q in others)}


def main(argv: list[str]) -> int:
    check = "--check" in argv
    langs = [a for a in argv if a != "--check"] or LANGS
    bad = False
    for lang in langs:
        if check:
            d = drift(lang)
            bad |= bool(d)
            print(d or f"{lang:7} adapter in sync")
        else:
            path(lang).write_text(render(lang))
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
