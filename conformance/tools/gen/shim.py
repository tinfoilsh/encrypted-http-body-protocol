"""The API shim of every SDK (handler.md sections 7 and 8), rendered into
the `shim:begin`..`shim:end` region of its client file. The template
`templates/<lang>/shim.*.j2` holds one macro per piece, each belonging to
the entry point its name starts with (PARTS); the profile's `shim` section
lists the pieces in the language's emission order (a class cannot be split)
and spells the native request, response and client types, how a parsed URL
splits into the parts MakeOrigin and Start take, how the native response is
read and rebuilt, and the residue's two body readers."""
from __future__ import annotations

import sys

from . import ROOT, macro, markers, profile

GEN = "generated by conformance/tools/gen_shim.py; do not edit"
LANGS = ["go", "python", "kotlin", "rust", "js", "swift"]
PROFILE_KEYS = ["files", "comment", "end_gap", "region_indent", "shim"]
PARTS = ["constructor", "request", "discover", "token", "selfcheck"]
GAP = {"python": "\n\n\n"}  # between pieces; one blank line elsewhere


def pieces(lang: str) -> dict[str, str]:
    """Piece -> rendered text, in emission order."""
    S = profile(lang).shim
    context = {k: v for k, v in S.items() if k != "pieces"}
    return {name: macro(lang, "shim", name, context) for name in S["pieces"]}


def render(lang: str) -> str:
    P = profile(lang)
    body = GAP.get(lang, "\n\n").join(pieces(lang).values())
    return markers.wrap(P.comment, "shim", GEN, body, P.region_indent.get("shim", ""), P.end_gap)


def path(lang: str):
    return ROOT / profile(lang).files["shim"]


def region(lang: str) -> tuple[str, str, str]:
    return markers.split(path(lang).read_text(), profile(lang).comment, "shim")


def drift(lang: str) -> dict[str, str]:
    """{"shim": unified diff} when the file's region differs from the rendering, else {}."""
    _, current, _ = region(lang)
    d = markers.diff(current, render(lang), f"{profile(lang).files['shim']} (shim)")
    return {"shim": d} if d else {}


def counts(lang: str) -> dict[str, int]:
    """Lines per PARTS entry, plus `generated` (the whole region, markers
    included) and `hand` (the file outside it; a Rust `#[cfg(test)]` module is
    not counted, tests are not the shim)."""
    out = {p: 0 for p in PARTS}
    for name, text in pieces(lang).items():
        out[name.split("_")[0]] += text.count("\n") + 1
    before, body, after = region(lang)
    after = after.split("#[cfg(test)]")[0] if lang == "rust" else after
    out["generated"] = body.count("\n") + 1
    out["hand"] = (before + after).strip("\n").count("\n") + 1
    return out


def write(lang: str) -> None:
    path(lang).write_text(markers.replace(path(lang).read_text(), profile(lang).comment, "shim", render(lang)))


def main(argv: list[str]) -> int:
    check = "--check" in argv
    langs = [a for a in argv if a != "--check"] or LANGS
    bad = False
    for lang in langs:
        if check:
            d = drift(lang)
            bad |= bool(d)
            print("".join(d.values()) or f"{lang:7} shim in sync")
        else:
            write(lang)
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
