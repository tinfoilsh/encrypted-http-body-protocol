"""The error classes and protocol constants of every SDK, whole files
rendered from the core (dafny/ehbp.dfy): the `CodeString` table and the
typed `const` block. Templates: `templates/<lang>/errors.*.j2` and
`protocol.*.j2`; the profile names the two files and the native spelling an
SDK already exposes for a code (`error_native`)."""
from __future__ import annotations

import shutil
import subprocess
import sys
from types import SimpleNamespace

from . import ROOT, dafny_decls, profile, template

GEN = "generated by conformance/tools/gen_errors.py from dafny/ehbp.dfy; do not edit"
LANGS = ["go", "python", "kotlin", "rust", "js"]
KINDS = ["errors", "protocol"]
PROFILE_KEYS = ["files", "error_native"]
CORE = ROOT / "dafny/ehbp.dfy"


def codes(lang: str) -> list[SimpleNamespace]:
    """Every code with a string: its Dafny name, the string, the SDK's spelling."""
    native = profile(lang).error_native
    return [SimpleNamespace(name=n, value=v, native=native.get(n, n)) for n, v in dafny_decls.code_strings(CORE.read_text())]


def consts() -> dict[str, str]:
    return dafny_decls.const_values(dafny_decls.parse_files([CORE]))


def rustfmt(text: str) -> str:
    """What `cargo fmt` would emit, so the drift check and rustfmt agree."""
    if not shutil.which("rustfmt"):
        return text
    done = subprocess.run(["rustfmt", "--edition", "2021", "--emit", "stdout"], input=text, capture_output=True, text=True)
    return done.stdout if done.returncode == 0 else text


def render() -> dict[str, str]:
    """Relative path -> file text, every language and kind."""
    out = {}
    k = consts()
    for lang in LANGS:
        for kind in KINDS:
            rel = profile(lang).files[kind]
            text = template(lang, kind).render(header=GEN, codes=codes(lang), k=k)
            out[rel] = rustfmt(text) if rel.endswith(".rs") else text
    return out


def main(argv: list[str]) -> int:
    check = "--check" in argv
    drift = []
    for rel, text in render().items():
        path = ROOT / rel
        if check:
            if not path.exists() or path.read_text() != text:
                drift.append(rel)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
    if check:
        for rel in drift:
            print(f"drift: {rel} (regenerate with python3 conformance/tools/gen.py errors)")
        return 1 if drift else 0
    print(f"wrote {len(LANGS) * len(KINDS)} files")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
