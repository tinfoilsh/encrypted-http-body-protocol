// DecryptResponse replaces resp.Body with the authenticated plaintext stream
// the token unlocks; the core's DecryptStart classifies the head, the pump
// drives the body. Closing the replacement body closes the original.
func (CoreAPI) DecryptResponse(resp *http.Response, token *SessionRecoveryToken) error {
	if token == nil {
		return protocol.Errorf(protocol.InvalidInput, "session recovery token is nil")
	}
	tok := core.Companion_Token_.Create_Token_(eventresidue.Seq(token.ExportedSecret), eventresidue.Seq(token.RequestEnc))
	x := eventresidue.ResponseExchange(resp.Body)
	x.Resume(ev.Companion_Default___.DecryptStart(tok, _dafny.IntOfInt(resp.StatusCode), eventresidue.HeaderSeq(resp.Header)))
	switch {
	case x.Failure != nil:
		return x.Failure
	case x.Passthrough:
		return protocol.Errorf(protocol.MissingResponseNonce, "missing %s header", protocol.ResponseNonceHeader)
	}
	resp.Header, resp.ContentLength, resp.Body = x.Headers, -1, &eventresidue.BodyReader{X: x}
	return nil
}

// EncryptRequest seals req.Body to publicKey in place through the core's
// request lane: req gains the encapsulated-key header and a streaming sealed
// body, and the published token is returned. A nil body is an error.
func (CoreAPI) EncryptRequest(publicKey []byte, req *http.Request) (*SessionRecoveryToken, error) {
	if req.Body == nil || req.Body == http.NoBody {
		return nil, protocol.Errorf(protocol.InvalidInput, "request has no body")
	}
	var session eventresidue.Session
	var token *SessionRecoveryToken
	// The core's Send carries the key header and the sealed upload, which move
	// onto req. The reply is one the core hands through, so the response lane
	// ends without touching the upload lane, which keeps sealing as req.Body is read.
	send := func(wire *http.Request) (*http.Response, error) {
		if tok := session.Token(); tok != nil {
			token = &SessionRecoveryToken{ExportedSecret: eventresidue.Bytes(tok.Dtor_exportedSecret()), RequestEnc: eventresidue.Bytes(tok.Dtor_requestEnc())}
			req.Header.Set(protocol.EncapsulatedKeyHeader, wire.Header.Get(protocol.EncapsulatedKeyHeader))
			req.Header.Set("Transfer-Encoding", "chunked")
			req.Body, req.ContentLength, req.GetBody = wire.Body, -1, nil
		}
		return &http.Response{StatusCode: http.StatusInternalServerError, Header: http.Header{}, Body: http.NoBody}, nil
	}
	origin := core.Companion_Origin_.Create_Origin_(eventresidue.Str("https"), eventresidue.Str("ehbp"), _dafny.IntOfInt(443))
	x := eventresidue.NewExchange(ev.Companion_Default___.Initial(origin, eventresidue.Seq(publicKey)), &session, send, &http.Request{}, req.Body)
	x.Feed(ev.Companion_Event_.Create_Start_(eventresidue.Str(req.Method), eventresidue.Str("https://ehbp/"),
		eventresidue.Str("https"), eventresidue.Str("ehbp"), _dafny.IntOfInt(0), false, false, eventresidue.HeaderSeq(nil), true))
	if token == nil {
		if x.Failure != nil {
			return nil, x.Failure
		}
		return nil, protocol.Errorf(protocol.InvalidInput, "request body is empty")
	}
	return token, nil
}
