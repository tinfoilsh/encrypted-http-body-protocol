// SessionRecoveryToken contains the pre-computed bytes needed to decrypt a
// response without holding a live HPKE context. Its JSON form is the core's
// (lowercase hex fields, SPEC 6.1.1), so it can be used later or in a different process.
type SessionRecoveryToken struct {
	ExportedSecret []byte `json:"exportedSecret"`
	RequestEnc     []byte `json:"requestEnc"`
}

func (t *SessionRecoveryToken) MarshalJSON() ([]byte, error) {
	return []byte(Core().FormatToken(Core().EncodeHex(t.ExportedSecret), Core().EncodeHex(t.RequestEnc))), nil
}

func (t *SessionRecoveryToken) UnmarshalJSON(data []byte) error {
	tok, err := Core().ParseToken(string(data))
	if err != nil {
		return err
	}
	*t = *tok
	return nil
}

