//! C ABI over the verified EHBP event core (dafny/ehbp_events.dfy) for the
//! Swift SDK: an opaque State, `Step` over a binary encoding of Event and
//! Action, and the pure helpers the API shim needs by op number. The
//! encoding is documented in conformance/spec/swift-ffi.md; the coders of
//! every type the ABI crosses and the op table are rendered from the Dafny
//! datatype declarations by conformance/tools/gen_ffi.py (the `ffi:begin`
//! region). Only the primitive coders and the six entry points are by hand.

use std::sync::Arc;

use ehbp_core::{
    EHBPEvents as ev,
    EHBP::{self as core, string_of, DafnyChar, DafnyInt, Sequence},
};

// ---------------------------------------------------------------------------
// Primitive coders: big-endian, u32 length prefixes, no alignment.

pub struct Writer(pub Vec<u8>);

impl Writer {
    fn u8(&mut self, v: u8) {
        self.0.push(v);
    }
    fn bool(&mut self, v: bool) {
        self.u8(v as u8);
    }
    fn u64(&mut self, v: u64) {
        self.0.extend_from_slice(&v.to_be_bytes());
    }
    fn int(&mut self, v: &DafnyInt) {
        self.0.extend_from_slice(&i64::from(v.clone()).to_be_bytes());
    }
    fn len(&mut self, n: usize) {
        self.0.extend_from_slice(&(n as u32).to_be_bytes());
    }
    fn bytes(&mut self, b: &[u8]) {
        self.len(b.len());
        self.0.extend_from_slice(b);
    }
    fn seq(&mut self, s: &Sequence<u8>) {
        self.bytes(&s.to_array());
    }
    fn str(&mut self, s: &Sequence<DafnyChar>) {
        self.bytes(s.iter().map(|c| c.0).collect::<String>().as_bytes());
    }
}

pub struct Reader<'a>(pub &'a [u8]);

/// Malformed input.
#[derive(Debug)]
pub struct Bad;

impl<'a> Reader<'a> {
    fn take(&mut self, n: usize) -> Result<&'a [u8], Bad> {
        if self.0.len() < n {
            return Err(Bad);
        }
        let (head, tail) = self.0.split_at(n);
        self.0 = tail;
        Ok(head)
    }
    fn u8(&mut self) -> Result<u8, Bad> {
        Ok(self.take(1)?[0])
    }
    fn bool(&mut self) -> Result<bool, Bad> {
        match self.u8()? {
            0 => Ok(false),
            1 => Ok(true),
            _ => Err(Bad),
        }
    }
    fn u64(&mut self) -> Result<u64, Bad> {
        Ok(u64::from_be_bytes(self.take(8)?.try_into().unwrap()))
    }
    fn int(&mut self) -> Result<DafnyInt, Bad> {
        Ok(DafnyInt::from(i64::from_be_bytes(self.take(8)?.try_into().unwrap())))
    }
    fn len(&mut self) -> Result<usize, Bad> {
        Ok(u32::from_be_bytes(self.take(4)?.try_into().unwrap()) as usize)
    }
    fn bytes(&mut self) -> Result<&'a [u8], Bad> {
        let n = self.len()?;
        self.take(n)
    }
    fn seq(&mut self) -> Result<Sequence<u8>, Bad> {
        Ok(Sequence::from_array_owned(self.bytes()?.to_vec()))
    }
    fn str(&mut self) -> Result<Sequence<DafnyChar>, Bad> {
        Ok(string_of(std::str::from_utf8(self.bytes()?).map_err(|_| Bad)?))
    }
    fn done(self) -> Result<(), Bad> {
        if self.0.is_empty() {
            Ok(())
        } else {
            Err(Bad)
        }
    }
}

