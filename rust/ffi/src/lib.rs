// The C ABI. Buffers handed out are boxed slices released by ehbp_free_buf; a panic inside the core is reported, never unwound into C.

pub struct EhbpState(Arc<ev::State>);

fn hand_out(out: *mut *mut u8, out_len: *mut usize, v: Vec<u8>) {
    let v = v.into_boxed_slice();
    // SAFETY: the caller supplies valid out pointers; a boxed slice has exact capacity.
    unsafe {
        *out_len = v.len();
        *out = Box::into_raw(v) as *mut u8;
    }
}

/// Runs `f` on the caller's thread and hands its buffer out; its error code,
/// or -1 when the core panicked. The core parses JSON iteratively, so a 512 KiB
/// Swift cooperative thread is enough (see `deep_problem_body_steps_from_a_small_stack`).
unsafe fn guarded(out: *mut *mut u8, out_len: *mut usize, f: impl FnOnce() -> Result<Vec<u8>, i32>) -> i32 {
    match std::panic::catch_unwind(std::panic::AssertUnwindSafe(f)) {
        Ok(Ok(v)) => {
            hand_out(out, out_len, v);
            0
        }
        Ok(Err(rc)) => rc,
        Err(_) => -1,
    }
}

/// # Safety
/// `input` points to `len` readable bytes.
#[no_mangle]
pub unsafe extern "C" fn ehbp_state_new(input: *const u8, len: usize) -> *mut EhbpState {
    let bytes = std::slice::from_raw_parts(input, len);
    let state = std::panic::catch_unwind(|| -> Result<Arc<ev::State>, Bad> {
        let mut r = Reader(bytes);
        let s = match r.u8()? {
            0 => {
                let origin = Arc::new(r.origin()?);
                ev::_default::Initial(&origin, &r.seq()?)
            }
            1 => ev::_default::ResponseOnly(&ev::_default::NoOrigin(), &Arc::new(r.token()?)),
            _ => return Err(Bad),
        };
        r.done()?;
        Ok(s)
    });
    match state {
        Ok(Ok(s)) => Box::into_raw(Box::new(EhbpState(s))),
        _ => std::ptr::null_mut(),
    }
}

/// # Safety
/// `state` came from ehbp_state_new and is freed once.
#[no_mangle]
pub unsafe extern "C" fn ehbp_state_free(state: *mut EhbpState) {
    if !state.is_null() {
        drop(Box::from_raw(state));
    }
}

/// # Safety
/// `state` is live; `event` points to `event_len` bytes; `out`/`out_len` are valid.
#[no_mangle]
pub unsafe extern "C" fn ehbp_step(state: *mut EhbpState, event: *const u8, event_len: usize, out: *mut *mut u8, out_len: *mut usize) -> i32 {
    let bytes = std::slice::from_raw_parts(event, event_len);
    let state = &mut *state;
    guarded(out, out_len, || {
        let mut r = Reader(bytes);
        let e = r.event().and_then(|e| r.done().map(|_| e)).map_err(|Bad| 1)?;
        let (next, acts) = ev::_default::Step(&state.0, &Arc::new(e));
        state.0 = next;
        let mut w = Writer(Vec::new());
        w.len(acts.cardinality_usize());
        for a in acts.iter() {
            w.action(&a);
        }
        Ok(w.0)
    })
}

/// # Safety
/// `state` is live; `out`/`out_len` are valid.
#[no_mangle]
pub unsafe extern "C" fn ehbp_keys_of(state: *const EhbpState, out: *mut *mut u8, out_len: *mut usize) -> i32 {
    let state = &*state;
    guarded(out, out_len, || {
        let mut w = Writer(Vec::new());
        w.option_bytes_bytes(&ev::_default::KeysOf(&state.0));
        Ok(w.0)
    })
}

/// # Safety
/// `input` points to `len` bytes; `out`/`out_len` are valid.
#[no_mangle]
pub unsafe extern "C" fn ehbp_call(op: u32, input: *const u8, len: usize, out: *mut *mut u8, out_len: *mut usize) -> i32 {
    let bytes = std::slice::from_raw_parts(input, len);
    guarded(out, out_len, || match call(op, bytes) {
        Ok(Some(v)) => Ok(v),
        Ok(None) => Err(2),
        Err(Bad) => Err(1),
    })
}

/// # Safety
/// `buf`/`len` came from one of the out pointers above and are freed once.
#[no_mangle]
pub unsafe extern "C" fn ehbp_free_buf(buf: *mut u8, len: usize) {
    if !buf.is_null() {
        drop(Box::from_raw(std::slice::from_raw_parts_mut(buf, len)));
    }
}

