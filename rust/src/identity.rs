impl SessionRecoveryToken {
    pub fn new(exported_secret: Vec<u8>, request_enc: Vec<u8>) -> Result<Self> {
        if !core::_default::ValidToken(&core_token(&exported_secret, &request_enc)) {
            return Err(Error::Coded(
                Code::InvalidToken,
                "token fields must be 32 bytes".into(),
            ));
        }
        Ok(Self {
            exported_secret,
            request_enc,
        })
    }

    pub(crate) fn from_core(token: &core::Token) -> Self {
        Self {
            exported_secret: bytes(token.exportedSecret()),
            request_enc: bytes(token.requestEnc()),
        }
    }

    /// The SPEC 6.1.1 JSON form; `parse_token` reads it back.
    pub fn to_json(&self) -> String {
        format_token(
            &encode_hex(&self.exported_secret),
            &encode_hex(&self.request_enc),
        )
    }

    /// Creates an incremental authenticated decryptor for this response.
    ///
    /// The caller must feed the response from its first frame and call
    /// [`ResponseDecryptor::finish`] when the encrypted source reaches EOF.
    pub fn response_decryptor(&self, response_nonce: &[u8]) -> Result<ResponseDecryptor> {
        let keys = derive_response_keys(&self.exported_secret, &self.request_enc, response_nonce)?;
        Ok(ResponseDecryptor {
            keys,
            dec: Arc::new(ev::Dec::Dec {
                pending: seq(&[]),
                next: 0,
                authenticated: false,
                requireFrame: false,
            }),
            failed: None,
        })
    }
}

