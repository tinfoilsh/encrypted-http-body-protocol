/// Runs one of the core's HKDF jobs (RFC 5869 as `JobStep`) to its output.
fn run_job(mut job: Arc<ev::Job>) -> Result<Vec<u8>> {
    loop {
        let mac = match ev::_default::JobAction(&job).as_ref() {
            ev::Action::HmacSha256 { key, data } => hmac_sha256(&bytes(key), &bytes(data)),
            _ => Vec::new(), // JobAction only ever asks for HMAC; the core rejects this by length
        };
        let step = ev::_default::JobStep(&job, &Arc::new(ev::Event::HmacResult { mac: seq(&mac) }));
        match step.as_ref() {
            ev::JobOut::Pending { job: next, .. } => job = next.clone(),
            ev::JobOut::Output { data } => return Ok(bytes(data)),
            ev::JobOut::JobFailed { code, message } => {
                return Err(error(code, &string(message), None))
            }
        }
    }
}

/// SPEC 4.4 (DeriveResponseKeys): the same jobs the core runs in `AwaitKeys`.
pub fn derive_response_keys(
    exported_secret: &[u8],
    request_enc: &[u8],
    response_nonce: &[u8],
) -> Result<ResponseKeyMaterial> {
    if !core::_default::ValidToken(&core_token(exported_secret, request_enc)) {
        return Err(Error::Coded(
            Code::InvalidInput,
            "token fields must be 32 bytes".into(),
        ));
    }
    if response_nonce.len() != RESPONSE_NONCE_LENGTH {
        return Err(Error::Coded(
            Code::InvalidInput,
            "response nonce must be 32 bytes".into(),
        ));
    }
    let salt = [request_enc, response_nonce].concat();
    let prk = run_job(ev::_default::Extract(&seq(&salt), &seq(exported_secret)))?;
    let expand = |label: &[u8], length: usize| {
        run_job(ev::_default::Expand(
            &seq(&prk),
            &seq(label),
            &nat::from(length),
        ))
    };
    Ok(ResponseKeyMaterial {
        key: expand(RESPONSE_KEY_LABEL, 32)?
            .try_into()
            .expect("core key length"),
        nonce_base: expand(RESPONSE_NONCE_LABEL, 12)?
            .try_into()
            .expect("core nonce length"),
    })
}

/// Incrementally decrypts an EHBP framed response: the core's pure decoder
/// (`Push`, `Finish`) splits frames, `ComputeNonce` and the residue's
/// `aead_open` open them. Feed encrypted bytes with [`Self::push`] and call
/// [`Self::finish`] at source EOF.
pub struct ResponseDecryptor {
    keys: ResponseKeyMaterial,
    dec: Arc<ev::Dec>,
    failed: Option<Code>,
}

impl ResponseDecryptor {
    /// Adds encrypted bytes and returns the newly authenticated plaintext
    /// frames that carry data. A decryptor that has failed stays failed.
    pub fn push(&mut self, data: &[u8]) -> Result<Vec<Vec<u8>>> {
        self.check()?;
        let (frames, dec, err) = ev::_default::Push(&self.dec, &seq(data));
        self.dec = dec;
        if let core::Option::Some { value } = err.as_ref() {
            return Err(self.fail(value));
        }
        let mut plaintext = Vec::new();
        for frame in frames.iter() {
            let nonce = core::_default::ComputeNonce(&seq(&self.keys.nonce_base), *frame.seqNo());
            let (ok, opened) =
                aead_open(&self.keys.key, &bytes(&nonce), &bytes(frame.ciphertext()));
            if !ok {
                return Err(self.fail(&Arc::new(core::Code::AeadDecryptFailed {})));
            }
            if !opened.is_empty() {
                plaintext.push(opened);
            }
        }
        Ok(plaintext)
    }

    /// Validates that source EOF occurred on a frame boundary.
    pub fn finish(&mut self) -> Result<()> {
        self.check()?;
        match ev::_default::Finish(&self.dec).as_ref() {
            core::Option::Some { value } => Err(self.fail(value)),
            core::Option::None {} => Ok(()),
        }
    }

    fn check(&self) -> Result<()> {
        match self.failed {
            Some(code) => Err(Error::Coded(code, "decryptor has failed".into())),
            None => Ok(()),
        }
    }

    fn fail(&mut self, code: &Arc<core::Code>) -> Error {
        let err = error(code, "encrypted response body", None);
        self.failed = err.code();
        err
    }
}

