// The FFI binding to the verified core (rust/ffi over dafny/ehbp_events.dfy):
// the types the ABI crosses with their binary coders (the `ffi:begin` region,
// rendered from the Dafny datatype declarations by conformance/tools/gen_ffi.py;
// the encoding is in conformance/spec/swift-ffi.md), the opaque core State with
// its step wrapper, and the pure helpers by op number.

import EHBPCore
import Foundation

// Primitive coders. A malformed buffer from the core is a codec bug on one
// side, so the reader stops the process rather than guess.

struct Writer {
    var data = Data()
    mutating func u8(_ v: UInt8) { data.append(v) }
    mutating func bool(_ v: Bool) { u8(v ? 1 : 0) }
    mutating func u64(_ v: UInt64) { withUnsafeBytes(of: v.bigEndian) { data.append(contentsOf: $0) } }
    mutating func int(_ v: Int64) { u64(UInt64(bitPattern: v)) }
    mutating func len(_ n: Int) { withUnsafeBytes(of: UInt32(n).bigEndian) { data.append(contentsOf: $0) } }
    mutating func bytes(_ b: Data) { len(b.count); data.append(b) }
    mutating func str(_ s: String) { bytes(Data(s.utf8)) }
}

struct Reader {
    let data: Data
    var pos: Int
    init(_ data: Data) { self.data = data; pos = data.startIndex }
    mutating func take(_ n: Int) -> Data {
        precondition(data.endIndex - pos >= n, "core: short buffer")
        defer { pos += n }
        return data[pos..<pos + n]
    }
    mutating func u8() -> UInt8 { take(1).first! }
    mutating func bool() -> Bool { u8() != 0 }
    mutating func u64() -> UInt64 { take(8).reduce(0) { $0 << 8 | UInt64($1) } }
    mutating func int() -> Int64 { Int64(bitPattern: u64()) }
    mutating func len() -> Int { Int(take(4).reduce(0) { $0 << 8 | UInt32($1) }) }
    mutating func bytes() -> Data { Data(take(len())) }
    mutating func str() -> String { String(decoding: bytes(), as: UTF8.self) }
    var atEnd: Bool { pos == data.endIndex }
}

// ffi:begin (generated by conformance/tools/gen_ffi.py from the Dafny datatypes; do not edit)
// Every type the ABI crosses, in declaration order: a constructor is its index,
// then its fields in order; a datatype with one constructor carries no tag;
// Option<T> is T?, Result<T> decodes to T or throws the core's error.

typealias Headers = [(String, String)]

enum Code: UInt8 {
    case invalidKeyConfig, unsupportedSuite, invalidEncapsulatedKey, hpkeSetupFailed, missingResponseNonce,
         unexpectedRedirect, invalidResponseNonce, duplicateResponseNonce, keyConfigMismatch,
         framingTruncated, chunkTooLarge, aeadDecryptFailed, sequenceOverflow, invalidToken, invalidInput,
         transport
}

struct Token { let exportedSecret: Data, requestEnc: Data }

struct Origin { let scheme: String, host: String, port: Int64 }

enum Stream: UInt8 {
    case requestBody, responseBody
}

enum BodyEnd {
    case more
    case done
    case aborted(code: Code)
}

enum Event {
    case start(verb: String, url: String, scheme: String, host: String, port: Int64, hasPort: Bool, hasUserinfo: Bool, headers: Headers, hasBody: Bool)
    case discoverStart
    case sessionBegun(generation: UInt64)
    case randomResult(data: Data)
    case x25519Result(point: Data)
    case hmacResult(mac: Data)
    case aeadSealResult(ciphertext: Data)
    case aeadOpenResult(ok: Bool, plaintext: Data)
    case responseHead(status: Int64, headers: Headers, redirected: Bool)
    case chunk(stream: Stream, data: Data, eof: Bool)
    case streamFailed(stream: Stream)
    case callerRead
    case callerClose
}

enum Action {
    case beginSession
    case publishToken(generation: UInt64, exportedSecret: Data, requestEnc: Data)
    case clearToken(generation: UInt64)
    case randomBytes(length: Int64)
    case x25519(scalar: Data, point: Data)
    case hmacSha256(key: Data, data: Data)
    case aeadSeal(key: Data, nonce: Data, plaintext: Data)
    case aeadOpen(key: Data, nonce: Data, ciphertext: Data)
    case send(verb: String, url: String, headers: Headers, hasBody: Bool)
    case write(data: Data, end: BodyEnd)
    case read(stream: Stream)
    case close(stream: Stream)
    case emitPlaintext(data: Data)
    case passthrough(status: Int64, headers: Headers, prefix: Data)
    case done(status: Int64, headers: Headers)
    case finished
    case discovered(publicKey: Data)
    case fail(code: Code, message: String)
}

struct SessionStore { let generation: UInt64, token: Token? }

enum SessionAction {
    case begin
    case publish(generation: UInt64, token: Token)
    case clear(generation: UInt64)
}

extension Writer {
    mutating func headers(_ v: Headers) { self.len(v.count); for e in v { self.str(e.0); self.str(e.1) } }
    mutating func code(_ v: Code) { u8(v.rawValue) }
    mutating func optionBytesBytes(_ v: (Data, Data)?) { if let v { u8(1); self.bytes(v.0); self.bytes(v.1) } else { u8(0) } }
    mutating func optionInt(_ v: Int64?) { if let v { u8(1); self.int(v) } else { u8(0) } }
    mutating func optionString(_ v: String?) { if let v { u8(1); self.str(v) } else { u8(0) } }
    mutating func optionBytes(_ v: Data?) { if let v { u8(1); self.bytes(v) } else { u8(0) } }
    mutating func optionToken(_ v: Token?) { if let v { u8(1); self.token(v) } else { u8(0) } }
    mutating func token(_ v: Token) { self.bytes(v.exportedSecret); self.bytes(v.requestEnc) }
    mutating func origin(_ v: Origin) { self.str(v.scheme); self.str(v.host); self.int(v.port) }
    mutating func stream(_ v: Stream) { u8(v.rawValue) }
    mutating func bodyEnd(_ v: BodyEnd) {
        switch v {
        case .more: u8(0)
        case .done: u8(1)
        case .aborted(let code): u8(2); self.code(code)
        }
    }
    mutating func event(_ v: Event) {
        switch v {
        case .start(let verb, let url, let scheme, let host, let port, let hasPort, let hasUserinfo, let headers, let hasBody): u8(0); self.str(verb); self.str(url); self.str(scheme); self.str(host); self.int(port); self.bool(hasPort); self.bool(hasUserinfo); self.headers(headers); self.bool(hasBody)
        case .discoverStart: u8(1)
        case .sessionBegun(let generation): u8(2); self.u64(generation)
        case .randomResult(let data): u8(3); self.bytes(data)
        case .x25519Result(let point): u8(4); self.bytes(point)
        case .hmacResult(let mac): u8(5); self.bytes(mac)
        case .aeadSealResult(let ciphertext): u8(6); self.bytes(ciphertext)
        case .aeadOpenResult(let ok, let plaintext): u8(7); self.bool(ok); self.bytes(plaintext)
        case .responseHead(let status, let headers, let redirected): u8(8); self.int(status); self.headers(headers); self.bool(redirected)
        case .chunk(let stream, let data, let eof): u8(9); self.stream(stream); self.bytes(data); self.bool(eof)
        case .streamFailed(let stream): u8(10); self.stream(stream)
        case .callerRead: u8(11)
        case .callerClose: u8(12)
        }
    }
    mutating func action(_ v: Action) {
        switch v {
        case .beginSession: u8(0)
        case .publishToken(let generation, let exportedSecret, let requestEnc): u8(1); self.u64(generation); self.bytes(exportedSecret); self.bytes(requestEnc)
        case .clearToken(let generation): u8(2); self.u64(generation)
        case .randomBytes(let length): u8(3); self.int(length)
        case .x25519(let scalar, let point): u8(4); self.bytes(scalar); self.bytes(point)
        case .hmacSha256(let key, let data): u8(5); self.bytes(key); self.bytes(data)
        case .aeadSeal(let key, let nonce, let plaintext): u8(6); self.bytes(key); self.bytes(nonce); self.bytes(plaintext)
        case .aeadOpen(let key, let nonce, let ciphertext): u8(7); self.bytes(key); self.bytes(nonce); self.bytes(ciphertext)
        case .send(let verb, let url, let headers, let hasBody): u8(8); self.str(verb); self.str(url); self.headers(headers); self.bool(hasBody)
        case .write(let data, let end): u8(9); self.bytes(data); self.bodyEnd(end)
        case .read(let stream): u8(10); self.stream(stream)
        case .close(let stream): u8(11); self.stream(stream)
        case .emitPlaintext(let data): u8(12); self.bytes(data)
        case .passthrough(let status, let headers, let prefix): u8(13); self.int(status); self.headers(headers); self.bytes(prefix)
        case .done(let status, let headers): u8(14); self.int(status); self.headers(headers)
        case .finished: u8(15)
        case .discovered(let publicKey): u8(16); self.bytes(publicKey)
        case .fail(let code, let message): u8(17); self.code(code); self.str(message)
        }
    }
    mutating func sessionStore(_ v: SessionStore) { self.u64(v.generation); self.optionToken(v.token) }
    mutating func sessionAction(_ v: SessionAction) {
        switch v {
        case .begin: u8(0)
        case .publish(let generation, let token): u8(1); self.u64(generation); self.token(token)
        case .clear(let generation): u8(2); self.u64(generation)
        }
    }
}

extension Reader {
    mutating func headers() -> Headers { (0..<len()).map { _ in (str(), str()) } }
    mutating func code() -> Code { Code(rawValue: u8())! }
    mutating func resultBytes() throws -> Data {
        switch u8() {
        case 0: return bytes()
        case 1: throw error(code(), str(), nil)
        default: preconditionFailure("core: bad Result tag")
        }
    }
    mutating func resultOrigin() throws -> Origin {
        switch u8() {
        case 0: return origin()
        case 1: throw error(code(), str(), nil)
        default: preconditionFailure("core: bad Result tag")
        }
    }
    mutating func resultToken() throws -> Token {
        switch u8() {
        case 0: return token()
        case 1: throw error(code(), str(), nil)
        default: preconditionFailure("core: bad Result tag")
        }
    }
    mutating func optionBytesBytes() -> (Data, Data)? {
        switch u8() {
        case 0: return nil
        case 1: return (bytes(), bytes())
        default: preconditionFailure("core: bad Option tag")
        }
    }
    mutating func optionInt() -> Int64? {
        switch u8() {
        case 0: return nil
        case 1: return int()
        default: preconditionFailure("core: bad Option tag")
        }
    }
    mutating func optionString() -> String? {
        switch u8() {
        case 0: return nil
        case 1: return str()
        default: preconditionFailure("core: bad Option tag")
        }
    }
    mutating func optionBytes() -> Data? {
        switch u8() {
        case 0: return nil
        case 1: return bytes()
        default: preconditionFailure("core: bad Option tag")
        }
    }
    mutating func optionToken() -> Token? {
        switch u8() {
        case 0: return nil
        case 1: return token()
        default: preconditionFailure("core: bad Option tag")
        }
    }
    mutating func token() -> Token { Token(exportedSecret: bytes(), requestEnc: bytes()) }
    mutating func origin() -> Origin { Origin(scheme: str(), host: str(), port: int()) }
    mutating func stream() -> Stream { Stream(rawValue: u8())! }
    mutating func bodyEnd() -> BodyEnd {
        switch u8() {
        case 0: return .more
        case 1: return .done
        case 2: return .aborted(code: code())
        default: preconditionFailure("core: bad BodyEnd tag")
        }
    }
    mutating func event() -> Event {
        switch u8() {
        case 0: return .start(verb: str(), url: str(), scheme: str(), host: str(), port: int(), hasPort: bool(), hasUserinfo: bool(), headers: headers(), hasBody: bool())
        case 1: return .discoverStart
        case 2: return .sessionBegun(generation: u64())
        case 3: return .randomResult(data: bytes())
        case 4: return .x25519Result(point: bytes())
        case 5: return .hmacResult(mac: bytes())
        case 6: return .aeadSealResult(ciphertext: bytes())
        case 7: return .aeadOpenResult(ok: bool(), plaintext: bytes())
        case 8: return .responseHead(status: int(), headers: headers(), redirected: bool())
        case 9: return .chunk(stream: stream(), data: bytes(), eof: bool())
        case 10: return .streamFailed(stream: stream())
        case 11: return .callerRead
        case 12: return .callerClose
        default: preconditionFailure("core: bad Event tag")
        }
    }
    mutating func action() -> Action {
        switch u8() {
        case 0: return .beginSession
        case 1: return .publishToken(generation: u64(), exportedSecret: bytes(), requestEnc: bytes())
        case 2: return .clearToken(generation: u64())
        case 3: return .randomBytes(length: int())
        case 4: return .x25519(scalar: bytes(), point: bytes())
        case 5: return .hmacSha256(key: bytes(), data: bytes())
        case 6: return .aeadSeal(key: bytes(), nonce: bytes(), plaintext: bytes())
        case 7: return .aeadOpen(key: bytes(), nonce: bytes(), ciphertext: bytes())
        case 8: return .send(verb: str(), url: str(), headers: headers(), hasBody: bool())
        case 9: return .write(data: bytes(), end: bodyEnd())
        case 10: return .read(stream: stream())
        case 11: return .close(stream: stream())
        case 12: return .emitPlaintext(data: bytes())
        case 13: return .passthrough(status: int(), headers: headers(), prefix: bytes())
        case 14: return .done(status: int(), headers: headers())
        case 15: return .finished
        case 16: return .discovered(publicKey: bytes())
        case 17: return .fail(code: code(), message: str())
        default: preconditionFailure("core: bad Action tag")
        }
    }
    mutating func sessionStore() -> SessionStore { SessionStore(generation: u64(), token: optionToken()) }
    mutating func sessionAction() -> SessionAction {
        switch u8() {
        case 0: return .begin
        case 1: return .publish(generation: u64(), token: token())
        case 2: return .clear(generation: u64())
        default: preconditionFailure("core: bad SessionAction tag")
        }
    }
}
// ffi:end

func decodeActions(_ data: Data) -> [Action] {
    var r = Reader(data)
    let acts = (0..<r.len()).map { _ in r.action() }
    precondition(r.atEnd, "core: trailing bytes")
    return acts
}

// The opaque core State and the step wrapper. Both lanes of an exchange step
// the same state, so Step is serialised by a lock.

final class CoreState: @unchecked Sendable {
    private let ptr: OpaquePointer
    private let lock = NSLock()

    /// Initial(origin, publicKey).
    init(origin: Origin, publicKey: Data) {
        var w = Writer()
        w.u8(0); w.origin(origin); w.bytes(publicKey)
        ptr = w.data.withUnsafeBytes { ehbp_state_new($0.baseAddress, $0.count) }!
    }

    /// ResponseOnly(token): decrypt or derive from a token alone (SPEC 6.2).
    init(token: (Data, Data)) {
        var w = Writer()
        w.u8(1); w.token(Token(exportedSecret: token.0, requestEnc: token.1))
        ptr = w.data.withUnsafeBytes { ehbp_state_new($0.baseAddress, $0.count) }!
    }

    deinit { ehbp_state_free(ptr) }

    func step(_ e: Event) -> [Action] {
        var w = Writer()
        w.event(e)
        lock.lock(); defer { lock.unlock() }
        return decodeActions(w.data.withUnsafeBytes { bytes in
            Core.buffer { ehbp_step(ptr, bytes.baseAddress, bytes.count, $0, $1) }
        })
    }

    /// KeysOf: the derived AES key and nonce base once Done was emitted.
    func keysOf() -> (key: Data, nonceBase: Data)? {
        var r = Reader(Core.buffer { ehbp_keys_of(ptr, $0, $1) })
        return r.optionBytesBytes()
    }
}

/// The pure core functions by op number (OPS in gen_ffi.py); the wrappers are
/// rendered by conformance/tools/gen_core.py.
enum Core {
    static func buffer(_ f: (UnsafeMutablePointer<UnsafeMutablePointer<UInt8>?>, UnsafeMutablePointer<Int>) -> Int32) -> Data {
        var out: UnsafeMutablePointer<UInt8>? = nil
        var len = 0
        let status = f(&out, &len)
        precondition(status == 0, "core: status \(status)")
        defer { ehbp_free_buf(out, len) }
        return Data(bytes: out!, count: len)
    }

    static func call(_ op: UInt32, _ w: Writer) -> Reader {
        Reader(w.data.withUnsafeBytes { bytes in buffer { ehbp_call(op, bytes.baseAddress, bytes.count, $0, $1) } })
    }

        // core:begin (generated by conformance/tools/gen_core.py; do not edit)
