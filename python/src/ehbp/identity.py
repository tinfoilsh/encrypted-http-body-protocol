def derive_keys(
    exported_secret: bytes, request_enc: bytes, response_nonce: bytes
) -> tuple[bytes, bytes]:
    """(AES-256-GCM key, base nonce) for one response."""
    x = _response_exchange(exported_secret, request_enc, response_nonce, [], 200)
    keys = x.state.phase.response.keys
    return r.bytes_(keys.key), r.bytes_(keys.baseNonce)


def decrypt(
    exported_secret: bytes, request_enc: bytes, response_nonce: bytes, chunks: Iterable[bytes],
    status: int = 200,
) -> Iterator[bytes]:
    """Decrypt a framed response body as it arrives (SPEC 6.2); each plaintext
    chunk is yielded only after its frame authenticates. The status decides
    whether an authenticated frame is required (SPEC 5.3)."""
    x = _response_exchange(exported_secret, request_enc, response_nonce, chunks, status)
    return decrypted_body(x)


def decrypted_body(x: r.Exchange) -> Iterator[bytes]:
    """The decrypted response body: each pull drives the core with Read until
    it emits plaintext, finishes or fails."""
    while not x.finished:
        r.feed(x, ev.Event_CallerRead())
        if x.plain:
            yield bytes(x.plain)
            x.plain.clear()
        if x.failure is not None:
            raise x.failure


_NO_ORIGIN = EHBP.Origin_Origin(r.str_(""), r.str_(""), EHBP.Option_None())


def _response_exchange(
    exported_secret: bytes, request_enc: bytes, response_nonce: bytes, chunks: Iterable[bytes],
    status: int,
) -> r.Exchange:
    """An exchange whose response lane starts at the head of a response to be
    decrypted with the token: the core's AwaitHead with no upload, past it."""
    token = EHBP.Token_Token(r.seq(bytes(exported_secret)), r.seq(bytes(request_enc)))
    state = ev.default__.Initial(_NO_ORIGIN, r.seq(b""))._replace(
        phase=ev.Phase_Exchanging(ev.Upload_NoUpload(), ev.Response_AwaitHead(True)), token=token
    )
    x = r.Exchange(state, r.Session(), None, None)
    x.chunks = iter(chunks)
    header = (r.str_(RESPONSE_NONCE_HEADER), r.str_(bytes(response_nonce).hex()))
    r.feed(x, ev.Event_ResponseHead(status, r.seq([header]), False))
    if x.failure is not None:
        raise x.failure
    return x
