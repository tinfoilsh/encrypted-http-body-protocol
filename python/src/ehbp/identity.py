def parse_config(config: bytes) -> bytes:
    """The public key of the first key configuration in `config` (RFC 9458, SPEC 3.2)."""
    return r.bytes_(r.unwrap(EHBP.default__.ParseConfig(r.seq(bytes(config)))))


def marshal_config(public_key: bytes) -> bytes:
    """The RFC 9458 key configuration for `publicKey` under the pinned suite; the key id is opaque and always 0."""
    return r.bytes_(r.unwrap(EHBP.default__.MarshalConfig(r.seq(bytes(public_key)))))


def check_public_key(public_key: bytes) -> bytes:
    """`publicKey` itself once the core has checked its length."""
    return r.bytes_(r.unwrap(EHBP.default__.CheckPublicKey(r.seq(bytes(public_key)))))


def nonce_for(nonce_base: bytes, seq_no: int) -> bytes:
    """`nonceBase` XOR `seqNo`, big-endian in the last 8 bytes (SPEC 4.4)."""
    return r.bytes_(r.unwrap(EHBP.default__.NonceFor(r.seq(bytes(nonce_base)), _uint64(seq_no))))


def encode_hex(data: bytes) -> str:
    """Lowercase hex."""
    return r.string(EHBP.default__.EncodeHex(r.seq(bytes(data))))


def decode_hex(hex: str) -> Optional[bytes]:
    """Strict hex decoding; none on any malformation."""
    o = EHBP.default__.DecodeHex(r.str_(hex))
    return r.bytes_(o.value) if o.is_Some else None


def format_token(exported_secret_hex: str, request_enc_hex: str) -> str:
    """The SPEC 6.1.1 JSON form of a token from its two hex fields."""
    return r.string(ev.default__.FormatToken(r.str_(exported_secret_hex), r.str_(request_enc_hex)))


def parse_token(json: str) -> SessionRecoveryToken:
    """The token of a SPEC 6.1.1 JSON document; any malformation is INVALID_TOKEN."""
    fields = ev.default__.ParseToken(r.str_(json))
    t = r.unwrap(EHBP.default__.ValidateTokenFields(*fields))
    return SessionRecoveryToken(r.bytes_(t.exportedSecret), r.bytes_(t.requestEnc))
