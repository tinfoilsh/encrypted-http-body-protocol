"""Helpers over the pure core: the RFC 9458 key config, session recovery
tokens (SPEC 6) and response decryption (SPEC 4.4, 6.2). Not public API: the
client uses them and this module is ``ehbp.core``, exposed for conformance and
tests only. The pure members are rendered by conformance/tools/gen_core.py.

A token carries the HPKE export secret and the request encapsulated key: all
that is needed to decrypt one response. It MUST be treated as key material.
"""

