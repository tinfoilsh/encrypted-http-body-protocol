def _uint64(n: int) -> int:
    if not isinstance(n, int) or isinstance(n, bool) or not 0 <= n < 1 << 64:
        raise InvalidInputError(f"sequence number out of uint64 range: {n!r}")
    return n

@dataclass(frozen=True, repr=False)
class SessionRecoveryToken:
    """The pre-computed bytes needed to decrypt one response (SPEC 6); key material."""

    exported_secret: bytes
    request_enc: bytes

    @property
    def json(self) -> str:
        """The SPEC 6.1.1 JSON form, which ``parse_token`` reads back."""
        return format_token(self.exported_secret.hex(), self.request_enc.hex())


