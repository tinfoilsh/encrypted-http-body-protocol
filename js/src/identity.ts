// Helpers over the pure core for the conformance adapter and the tests only
// (handler.md section 7): config parse and marshal, token parse and format,
// hex, nonce, key derivation, and decrypting a response from a token. Not
// public API; nothing an application needs lives here. The pure members are
// rendered by conformance/tools/gen_core.py.
import type BigNumber from 'bignumber.js';
import { type Job, Event, Token, core as pure, ev, int } from './core.js';
import { bytes, error, hmacSha256, seq, str, string, unwrap } from './residue.js';
import { InvalidInputError } from './errors.js';
import { decryptWithToken } from './client.js';

/** `n` as the core's uint64; the typed ports reject anything else at compile time, so this is the one place a range check lives. */
const uint64 = (n: bigint | number): BigNumber => {
  if (typeof n === 'number' ? !Number.isSafeInteger(n) || n < 0 : n < 0n || n > 0xffffffffffffffffn) throw new InvalidInputError(`sequence number out of uint64 range: ${n}`);
  return int(n);
};

/** The pre-computed bytes needed to decrypt one response (SPEC 6). */
export interface SessionRecoveryToken {
  exportedSecret: Uint8Array;
  requestEnc: Uint8Array;
}

/** Runs one of the core's HKDF jobs to its output (JobStep over HmacResult events). */
async function job(j: Job): Promise<Uint8Array> {
  for (;;) {
    const a = ev.JobAction(j);
    const out = ev.JobStep(j, Event.create_HmacResult(seq(await hmacSha256(bytes(a.dtor_key), bytes(a.dtor_data)))));
    if (out.is_Output) return bytes(out.dtor_data);
    if (out.is_JobFailed) throw error(out.dtor_code, string(out.dtor_message));
    j = out.dtor_job;
  }
}

export const core = {
  // core:begin (generated by conformance/tools/gen_core.py; do not edit)
  // core: the pure helpers over the core, bytes and strings in and out (handler.md section 7).
  /** The public key of the first key configuration in `config` (RFC 9458, SPEC 3.2). */
  parseConfig(config: Uint8Array): Uint8Array {
    return bytes(unwrap(pure.ParseConfig(seq(config))));
  },
  /** The RFC 9458 key configuration for `publicKey` under the pinned suite; the key id is opaque and always 0. */
  marshalConfig(publicKey: Uint8Array): Uint8Array {
    return bytes(unwrap(pure.MarshalConfig(seq(publicKey))));
  },
  /** `publicKey` itself once the core has checked its length. */
  checkPublicKey(publicKey: Uint8Array): Uint8Array {
    return bytes(unwrap(pure.CheckPublicKey(seq(publicKey))));
  },
  /** `nonceBase` XOR `seqNo`, big-endian in the last 8 bytes (SPEC 4.4). */
  nonceFor(nonceBase: Uint8Array, seqNo: bigint | number): Uint8Array {
    return bytes(unwrap(pure.NonceFor(seq(nonceBase), uint64(seqNo))));
  },
  /** Lowercase hex. */
  encodeHex(data: Uint8Array): string {
    return string(pure.EncodeHex(seq(data)));
  },
  /** Strict hex decoding; none on any malformation. */
  decodeHex(hex: string): Uint8Array | undefined {
    let o = pure.DecodeHex(str(hex));
    return o.is_Some ? bytes(o.dtor_value) : undefined;
  },
  /** The SPEC 6.1.1 JSON form of a token from its two hex fields. */
  formatToken(exportedSecretHex: string, requestEncHex: string): string {
    return string(ev.FormatToken(str(exportedSecretHex), str(requestEncHex)));
  },
  /** The token of a SPEC 6.1.1 JSON document; any malformation is INVALID_TOKEN. */
  parseToken(json: string): SessionRecoveryToken {
    let t = unwrap(pure.ValidateTokenFields(...ev.ParseToken(str(json))));
    return { exportedSecret: bytes(t.dtor_exportedSecret), requestEnc: bytes(t.dtor_requestEnc) };
  },
  // core:end
  /** Response key derivation (SPEC 4.4), the core's HKDF jobs as its response lane runs them. */
  async deriveKeys(exportedSecret: Uint8Array, requestEnc: Uint8Array, responseNonce: Uint8Array): Promise<{ key: Uint8Array; nonceBase: Uint8Array }> {
    if (!pure.ValidToken(Token.create_Token(seq(exportedSecret), seq(requestEnc)))) throw new InvalidInputError('token fields must be 32 bytes');
    if (responseNonce.length !== pure.ResponseNonceLength.toNumber()) throw new InvalidInputError('response nonce must be 32 bytes');
    const prk = await job(ev.Extract(seq(new Uint8Array([...requestEnc, ...responseNonce])), seq(exportedSecret)));
    const key = await job(ev.Expand(seq(prk), pure.Ascii(pure.ResponseKeyLabel), pure.KeyLength));
    const nonceBase = await job(ev.Expand(seq(prk), pure.Ascii(pure.ResponseNonceLabel), pure.NonceLength));
    return { key, nonceBase };
  },
  decryptWithToken,
};
